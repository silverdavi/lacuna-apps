test('[A6] export CSV copies the expected text to the clipboard', async ({ page, context }) => {
  // The spec names a toast; a status region or alert is the accessible equivalent, so accept any of them.
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await page.getByLabel('Name').fill('Alice')
  await page.getByRole('button', { name: 'Add member' }).click()
  await page.getByRole('listitem', { name: /Alice/ }).getByRole('button', { name: 'Assign chore' }).click()
  await page.getByLabel('Chore name').fill('Dishes')
  await page.getByRole('button', { name: 'Save' }).click()
  await page.getByRole('tab', { name: 'Chores' }).click()
  await page.getByRole('row', { name: /Alice.*Dishes/ }).getByRole('checkbox').click()
  await page.getByRole('button', { name: 'Export CSV' }).click()
  const notice = page
    .getByText('CSV copied to clipboard')
    .or(page.getByRole('status').getByText('CSV copied to clipboard'))
    .or(page.getByRole('alert').getByText('CSV copied to clipboard'))
  await expect(notice.first()).toBeVisible()
  const clipboard = await page.evaluate(() => navigator.clipboard.readText().catch(() => ''))
  expect(clipboard).toBe('Member,Chore,Status\nAlice,Dishes,Done\n')
})

