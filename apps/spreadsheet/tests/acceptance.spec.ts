test('[A5] clicking Add sheet creates a Sheet2 tab, switches to it, and A1 is blank', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Add sheet' }).click()
  const tab = page.getByRole('tab', { name: 'Sheet2' })
  await expect(tab).toBeVisible()
  await expect(tab).toHaveAttribute('aria-selected', 'true')
  await expect(page.getByLabel('A1')).not.toHaveText(/\S/)
})

test('[A6] clicking the Sheet1 tab returns to the first sheet with A1 10 and B1 20', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('A1').click()
  await page.keyboard.type('10')
  await page.keyboard.press('Enter')
  await page.getByLabel('B1').click()
  await page.keyboard.type('=A1*2')
  await page.keyboard.press('Enter')
  await page.getByRole('button', { name: 'Add sheet' }).click()
  await page.getByRole('tab', { name: 'Sheet1' }).click()
  await expect(page.getByLabel('A1')).toContainText('10')
  await expect(page.getByLabel('B1')).toContainText('20')
})

test('[A7] clicking Export CSV copies the current sheet data to the clipboard', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await page.getByLabel('A1').click()
  await page.keyboard.type('10')
  await page.keyboard.press('Enter')
  await page.getByLabel('B1').click()
  await page.keyboard.type('=A1*2')
  await page.keyboard.press('Enter')
  await page.getByLabel('A2').click()
  await page.keyboard.type('5')
  await page.keyboard.press('Enter')
  await page.getByLabel('B2').click()
  await page.keyboard.type('=A2*2')
  await page.keyboard.press('Enter')
  await page.getByRole('button', { name: 'Export CSV' }).click()
  const text = await page.evaluate(async () => navigator.clipboard.readText())
  expect(text).toBe('A,B\n10,20\n5,10')
})

test('[A8] typing =A1+100 into B1 shows 110 in B1, replacing the previous value', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('A1').click()
  await page.keyboard.type('10')
  await page.keyboard.press('Enter')
  await page.getByLabel('B1').click()
  await page.keyboard.type('=A1*2')
  await page.keyboard.press('Enter')
  await page.getByLabel('B1').click()
  await page.keyboard.type('=A1+100')
  await page.keyboard.press('Enter')
  await expect(page.getByLabel('B1')).toContainText('110')
})

test('[A9] reload keeps the sheet named Sheet1 with A1 10 and B1 110', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('A1').click()
  await page.keyboard.type('10')
  await page.keyboard.press('Enter')
  await page.getByLabel('B1').click()
  await page.keyboard.type('=A1+100')
  await page.keyboard.press('Enter')
  await page.reload()
  await expect(page.getByRole('tab', { name: 'Sheet1' })).toBeVisible()
  await expect(page.getByLabel('A1')).toContainText('10')
  await expect(page.getByLabel('B1')).toContainText('110')
})
