import { expect, test, type Locator, type Page } from '@playwright/test'

const scale = (page: Page): Locator => page.getByText(/^Scale factor: /)
const flourRow = (page: Page): Locator => page.getByRole('row', { name: /Flour/ })
const saltRow = (page: Page): Locator => page.getByRole('row', { name: /Salt/ })

test('[A1] with no ingredients the page shows the heading, No ingredients yet, and Scale factor: 1.00', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Recipe Scaler', exact: true })).toBeVisible()
  await expect(page.getByText('No ingredients yet', { exact: true })).toBeVisible()
  await expect(scale(page)).toHaveText('Scale factor: 1.00')
})

test('[A2] adding Flour 1 1/2 cups adds a table row and removes No ingredients yet', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Quantity', { exact: true }).fill('1 1/2')
  await page.getByLabel('Unit', { exact: true }).selectOption({ label: 'cups' })
  await page.getByLabel('Ingredient', { exact: true }).fill('Flour')
  await page.getByRole('button', { name: 'Add ingredient', exact: true }).click()
  const row = flourRow(page)
  await expect(row).toContainText('Flour')
  await expect(row).toContainText('1 1/2')
  await expect(row).toContainText('cups')
  await expect(page.getByText('No ingredients yet', { exact: true })).toBeHidden()
})

