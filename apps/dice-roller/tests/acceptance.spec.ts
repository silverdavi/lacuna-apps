test('[A4] typing 3d6 and rolling with seed 7 shows Total 10 and three d6 rows with values 3, 4, 3', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Seed').fill('7')
  await page.getByLabel('Expression').fill('3d6')
  await page.getByRole('button', { name: 'Roll' }).click()
  await expect(page.getByText('Total: 10')).toBeVisible()
  const table = page.getByRole('table')
  const rows = table.locator('tr', { has: page.getByText('d6', { exact: true }) })
  await expect(rows).toHaveCount(3)
  const first = rows.nth(0)
  const second = rows.nth(1)
  const third = rows.nth(2)
  await expect(first.locator('td').last()).toHaveText('3')
  await expect(second.locator('td').last()).toHaveText('4')
  await expect(third.locator('td').last()).toHaveText('3')
})

