test('[A7] rolling 2d6+3 then reloading still shows Total 12 and a 2d6 row', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Expression').fill('2d6+3')
  await page.getByRole('button', { name: 'Roll' }).click()
  await page.reload()
  await expect(page.getByText('Total: 12')).toBeVisible()
  const table = page.getByRole('table')
  const row = table.locator('tr', { has: page.getByText('2d6', { exact: true }) })
  await expect(row).toBeVisible()
})

