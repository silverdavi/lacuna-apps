import { expect, test } from '@playwright/test'

test('[A1] with no input, shows heading, intro text, and empty result area', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Dice Roller' })).toBeVisible()
  await expect(page.getByText('Enter a dice expression')).toBeVisible()
  await expect(page.getByText('No rolls yet')).toBeVisible()
})

test('[A2] typing 2d6+3 and rolling shows Total 12 and a 2d6 row with a value between 2 and 12', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Expression').fill('2d6+3')
  await page.getByRole('button', { name: 'Roll' }).click()
  await expect(page.getByText('Total: 12')).toBeVisible()
  const table = page.getByRole('table')
  await expect(table).toBeVisible()
  const row = table.locator('tr', { has: page.getByText('2d6', { exact: true }) })
  await expect(row).toBeVisible()
  const value = await row.locator('td').last().innerText()
  expect(Number(value)).toBeGreaterThanOrEqual(2)
  expect(Number(value)).toBeLessThanOrEqual(12)
})

