test('[A9] reload keeps both polls and their vote counts', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Question').fill('Favorite Color?')
  let choices = page.getByLabel(/^Choice \d+$/)
  await choices.first().fill('Red')
  await choices.nth(1).fill('Blue')
  await page.getByRole('button', { name: 'Create poll' }).click()
  await page.getByRole('button', { name: 'Vote Red' }).click()
  await page.getByLabel('Question').fill('Best Fruit?')
  choices = page.getByLabel(/^Choice \d+$/)
  await choices.first().fill('Apple')
  await choices.nth(1).fill('Banana')
  await choices.nth(2).fill('Cherry')
  await page.getByRole('button', { name: 'Create poll' }).click()
  await page.getByRole('button', { name: 'Vote Apple' }).click()
  await page.reload()
  await expect(page.getByText('Favorite Color?')).toBeVisible()
  await expect(page.getByText('Red').locator('..').getByText('1')).toBeVisible()
  await expect(page.getByText('Blue').locator('..').getByText('0')).toBeVisible()
  await expect(page.getByText('Best Fruit?')).toBeVisible()
  await expect(page.getByText('Apple').locator('..').getByText('1')).toBeVisible()
  await expect(page.getByText('Banana').locator('..').getByText('0')).toBeVisible()
  await expect(page.getByText('Cherry').locator('..').getByText('0')).toBeVisible()
})
