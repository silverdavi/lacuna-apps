import { expect, test } from '@playwright/test'

test('[A1] with no polls the page shows the heading and "No polls yet"', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Poll Maker' })).toBeVisible()
  await expect(page.getByText('No polls yet')).toBeVisible()
})

test('[A2] create a two-choice poll and its card shows the choices with zero votes', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Question').fill('Favorite Color?')
  const choices = page.getByLabel(/^Choice \d+$/)
  await choices.first().fill('Red')
  await choices.nth(1).fill('Blue')
  await page.getByRole('button', { name: 'Create poll' }).click()
  await expect(page.getByText('No polls yet')).toBeHidden()
  const card = page.getByText('Favorite Color?').first()
  await expect(card).toBeVisible()
  await expect(card.locator('..').getByText('Red')).toBeVisible()
  await expect(card.locator('..').getByText('Blue')).toBeVisible()
  await expect(card.locator('..').getByText('0')).toHaveCount(2)
})

