import { expect, test } from '@playwright/test'

test('[A1] heading and empty state', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Bucket List Tracker' })).toBeVisible()
  await expect(page.getByText('No entries yet')).toBeVisible()
})

test('[A2] add an entry', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('tab', { name: 'Entries' }).click()
  await page.getByLabel('Title').fill('Skydive')
  await page.getByLabel('Category').selectOption({ label: 'Adventure' })
  await page.getByRole('button', { name: 'Add entry' }).click()
  await expect(page.getByText('Skydive')).toBeVisible()
  await expect(page.getByText('Adventure')).toBeVisible()
  await expect(page.getByText('No entries yet')).toHaveCount(0)
})

