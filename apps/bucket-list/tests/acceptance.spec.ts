test('[A6] export CSV', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('tab', { name: 'Entries' }).click()
  await page.getByLabel('Title').fill('Skydive')
  await page.getByLabel('Category').selectOption({ label: 'Adventure' })
  await page.getByRole('button', { name: 'Add entry' }).click()
  await page.getByRole('button', { name: 'Add step' }).click()
  await page.getByLabel('Step').fill('Book jump')
  await page.getByLabel('Step').press('Enter')
  await page.getByRole('checkbox', { name: 'Book jump' }).check()
  const [download] = await Promise.all([
    page.waitForEvent('download'),
    page.getByRole('button', { name: 'Export CSV' }).click(),
  ])
  await expect(page.getByText('Exported 1 entry')).toBeVisible()
  const path = await download.path()
  const { readFileSync } = await import('fs')
  const csv = readFileSync(path!, 'utf8')
  expect(csv).toContain('Skydive,Adventure,1/1')
})

