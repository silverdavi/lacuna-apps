test('[A5] export CSV copies header and row to clipboard', async ({ page }) => {
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await open(page)
  await page.getByRole('button', { name: 'New order' }).click()
  await page.getByLabel('Vendor').fill('Acme Corp')
  await page.getByLabel('Order date').fill('2024-01-15')
  await page.getByRole('button', { name: 'Add line item' }).click()
  await page.getByLabel('Description').fill('Widget')
  await page.getByLabel('Quantity').fill('10')
  await page.getByLabel('Unit price').fill('25.00')
  await page.getByLabel('Discount %').fill('5')
  await page.getByLabel('Tax %').fill('8')
  await page.getByRole('button', { name: 'Save' }).click()
  await page.getByRole('button', { name: 'Export CSV' }).click()
  const csv = await page.evaluate(() => navigator.clipboard.readText())
  expect(csv).toContain('vendor,order_date,description,quantity,unit_price,discount_pct,tax_pct,total')
  expect(csv).toContain('Acme Corp,2024-01-15,Widget,10,25.00,5,8,261.00')
})

