import { expect, test } from '@playwright/test'

test('[A1] heading and empty state', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Packing List' })).toBeVisible()
  await expect(page.getByText('No items yet')).toBeVisible()
})

test('[A2] adding an item', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Item name').fill('Passport')
  await page.getByRole('button', { name: 'Add item' }).click()
  await expect(page.getByText('No items yet')).toHaveCount(0)
  const item = page.getByRole('listitem').filter({ hasText: 'Passport' })
  await expect(item).toBeVisible()
  await expect(item.locator('input[type="checkbox"]')).not.toBeChecked()
})

test('[A3] checking an item updates progress', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Item name').fill('Passport')
  await page.getByRole('button', { name: 'Add item' }).click()
  await page.getByLabel('Item name').fill('Toothbrush')
  await page.getByRole('button', { name: 'Add item' }).click()
  await page.getByRole('listitem').filter({ hasText: 'Passport' }).locator('input[type="checkbox"]').click()
  await expect(page.getByText('1 of 2 packed')).toBeVisible()
})

test('[A4] inline edit', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Item name').fill('Passport')
  await page.getByRole('button', { name: 'Add item' }).click()
  await page.getByLabel('Item name').fill('Toothbrush')
  await page.getByRole('button', { name: 'Add item' }).click()
  await page.getByRole('listitem').filter({ hasText: 'Toothbrush' }).getByRole('button', { name: 'Edit' }).click()
  const editField = page.getByRole('listitem').filter({ hasText: 'Toothbrush' }).locator('input')
  await editField.fill('Toothpaste')
  await editField.press('Enter')
  await expect(page.getByRole('listitem').filter({ hasText: 'Toothpaste' })).toBeVisible()
  await expect(page.getByRole('listitem').filter({ hasText: 'Toothbrush' })).toHaveCount(0)
})

test('[A5] copy summary', async ({ page }) => {
  await page.goto('/')
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.getByLabel('Item name').fill('Passport')
  await page.getByRole('button', { name: 'Add item' }).click()
  await page.getByLabel('Item name').fill('Toothpaste')
  await page.getByRole('button', { name: 'Add item' }).click()
  await page.getByRole('listitem').filter({ hasText: 'Passport' }).locator('input[type="checkbox"]').click()
  await page.getByRole('button', { name: 'Copy summary' }).click()
  expect(await page.evaluate(() => navigator.clipboard.readText())).toBe('Packed: Passport\nRemaining: Toothpaste')
})

test('[A6] trip details tab', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('tab', { name: 'Trip details' }).click()
  await page.getByLabel('Destination').fill('Paris')
  await page.getByLabel('Departure date').fill('2025-06-15')
  await page.getByRole('button', { name: 'Save' }).click()
  await page.getByRole('tab', { name: 'Items' }).click()
  await page.getByRole('tab', { name: 'Trip details' }).click()
  await expect(page.getByLabel('Destination')).toHaveValue('Paris')
  await expect(page.getByLabel('Departure date')).toHaveValue('2025-06-15')
})

test('[A7] Alt+ArrowUp reorders item', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Item name').fill('Passport')
  await page.getByRole('button', { name: 'Add item' }).click()
  await page.getByLabel('Item name').fill('Toothpaste')
  await page.getByRole('button', { name: 'Add item' }).click()
  await page.getByRole('listitem').filter({ hasText: 'Toothpaste' }).focus()
  await page.keyboard.press('Alt+ArrowUp')
  await expect(page.getByRole('list').locator('li').first()).toContainText('Toothpaste')
  await expect(page.getByRole('list').locator('li').first()).not.toContainText('Passport')
})

test('[A8] delete item', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Item name').fill('Passport')
  await page.getByRole('button', { name: 'Add item' }).click()
  await page.getByLabel('Item name').fill('Toothpaste')
  await page.getByRole('button', { name: 'Add item' }).click()
  await page.getByRole('listitem').filter({ hasText: 'Passport' }).locator('input[type="checkbox"]').click()
  await page.getByRole('listitem').filter({ hasText: 'Toothpaste' }).getByRole('button', { name: 'Delete' }).click()
  await expect(page.getByText('1 of 1 packed')).toBeVisible()
  await expect(page.getByRole('listitem').filter({ hasText: 'Passport' })).toBeVisible()
  await expect(page.getByRole('listitem').filter({ hasText: 'Toothpaste' })).toHaveCount(0)
})

test('[A9] state survives reload', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Item name').fill('Passport')
  await page.getByRole('button', { name: 'Add item' }).click()
  await page.getByRole('listitem').filter({ hasText: 'Passport' }).locator('input[type="checkbox"]').click()
  await page.getByRole('tab', { name: 'Trip details' }).click()
  await page.getByLabel('Destination').fill('Paris')
  await page.getByLabel('Departure date').fill('2025-06-15')
  await page.getByRole('button', { name: 'Save' }).click()
  await page.reload()
  await expect(page.getByRole('listitem').filter({ hasText: 'Passport' }).locator('input[type="checkbox"]')).toBeChecked()
  await page.getByRole('tab', { name: 'Trip details' }).click()
  await expect(page.getByLabel('Destination')).toHaveValue('Paris')
  await expect(page.getByLabel('Departure date')).toHaveValue('2025-06-15')
})
