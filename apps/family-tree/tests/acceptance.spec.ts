import { expect, test } from '@playwright/test'

test('[A1] shows heading and empty state', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Family Tree Visualizer' })).toBeVisible()
  await expect(page.getByText('No people yet')).toBeVisible()
})

test('[A2] adds a person from the Add Person form', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Name').fill('Alice')
  await page.getByLabel('Birth date').fill('1980-05-15')
  await page.getByRole('button', { name: 'Add person' }).click()
  await expect(page.getByText('No people yet')).not.toBeVisible()
  const alice = page.locator('li').filter({ hasText: 'Alice' }).first()
  await expect(alice).toHaveText(/Alice/)
  await expect(alice).toHaveText(/b\. 1980-05-15/)
})

test('[A3] adds a child under a parent', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Name').fill('Alice')
  await page.getByLabel('Birth date').fill('1980-05-15')
  await page.getByRole('button', { name: 'Add person' }).click()
  await page.getByRole('button', { name: 'Add child', exact: true }).first().click()
  await page.getByLabel('Name').fill('Bob')
  await page.getByLabel('Birth date').fill('2010-03-22')
  await page.getByRole('button', { name: 'Add person' }).click()
  const bob = page.locator('li').filter({ hasText: 'Bob' }).first()
  await expect(bob).toHaveText(/Bob/)
  await expect(bob).toHaveText(/b\. 2010-03-22/)
  await expect(page.getByText('Bob')).toBeVisible()
  const bobBox = await page.getByText('Bob').first().boundingBox()
  const aliceBox = await page.getByText('Alice').first().boundingBox()
  expect(bobBox).not.toBeNull()
  expect(aliceBox).not.toBeNull()
  expect(bobBox!.x).toBeGreaterThan(aliceBox!.x)
})

