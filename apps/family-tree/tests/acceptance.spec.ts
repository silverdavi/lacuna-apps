test('[A7] export JSON copies to clipboard', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await page.getByLabel('Name').fill('Alice')
  await page.getByLabel('Birth date').fill('1980-05-15')
  await page.getByRole('button', { name: 'Add person' }).click()
  await page.getByRole('button', { name: 'Add child', exact: true }).first().click()
  await page.getByLabel('Name').fill('Bob')
  await page.getByLabel('Birth date').fill('2010-03-22')
  await page.getByRole('button', { name: 'Add person' }).click()
  await page.getByRole('tab', { name: 'Graph' }).click()
  await page.getByRole('button', { name: 'Export JSON' }).click()
  const clip = await page.evaluate(() => navigator.clipboard.readText())
  expect(clip).toContain('"name":"Alice"')
  expect(clip).toContain('"name":"Bob"')
})

