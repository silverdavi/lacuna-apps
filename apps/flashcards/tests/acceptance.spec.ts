test('[A5] grading Good closes session, marks card due tomorrow', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'New deck' }).click()
  await page.getByLabel('Deck name').fill('Spanish')
  await page.getByRole('button', { name: 'Save deck' }).click()
  await page.getByRole('button', { name: 'Add card' }).click()
  await page.getByLabel('Front').fill('gato')
  await page.getByLabel('Back').fill('cat')
  await page.getByRole('button', { name: 'Save card' }).click()
  await page.getByRole('button', { name: 'Start study' }).click()
  await page.getByRole('button', { name: 'Reveal' }).click()
  await page.getByRole('button', { name: 'Good' }).click()
  await expect(page.getByText('Reveal')).toHaveCount(0)
  await expect(page.getByText('1 due')).toBeVisible()
  const queueItem = page.locator('li').filter({ hasText: 'gato' })
  await expect(queueItem).toBeVisible()
  const tomorrow = new Date(Date.now() + 86_400_000)
  await expect(queueItem.getByText(tomorrow.toDateString())).toBeVisible()
})

