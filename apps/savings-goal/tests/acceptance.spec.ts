import { expect, test } from '@playwright/test'

test('[A1] empty state shows heading, "No goals yet" and "New goal" button', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Savings Goal Tracker' })).toBeVisible()
  await expect(page.getByText('No goals yet')).toBeVisible()
  await expect(page.getByRole('button', { name: 'New goal' })).toBeVisible()
})

test('[A2] create a goal with name, target amount and deadline', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'New goal' }).click()
  await page.getByLabel('Goal name').fill('Emergency Fund')
  await page.getByLabel('Target amount').fill('5000')
  await page.getByLabel('Deadline').fill('2025-12-31')
  await page.getByRole('button', { name: 'Save goal' }).click()
  await expect(page.getByText('No goals yet')).not.toBeVisible()
  const item = page.getByRole('listitem', { name: /Emergency Fund/ })
  await expect(item).toContainText('$0.00 / $5,000.00')
  await expect(item).toContainText('0%')
})

