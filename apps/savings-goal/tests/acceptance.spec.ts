test('[A8] Export CSV copies the expected CSV to the clipboard', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await page.getByRole('button', { name: 'New goal' }).click()
  await page.getByLabel('Goal name').fill('Emergency Fund')
  await page.getByLabel('Target amount').fill('5000')
  await page.getByLabel('Deadline').fill('2025-12-31')
  await page.getByRole('button', { name: 'Save goal' }).click()
  await page.getByRole('button', { name: 'Add deposit' }).click()
  await page.getByLabel('Amount').fill('250.75')
  await page.getByRole('button', { name: 'Save deposit' }).click()
  await page.getByRole('button', { name: 'Export CSV' }).click()
  const text = await page.evaluate(() => navigator.clipboard.readText())
  expect(text).toBe('Goal,Target,Saved,Percent\nEmergency Fund,5000.00,250.75,5')
})

