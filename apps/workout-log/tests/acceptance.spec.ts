test('[A6] exports workouts to CSV', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Add workout' }).click()
  await page.getByLabel('Exercise').fill('Bench Press')
  await page.getByLabel('Reps').fill('8')
  await page.getByLabel('Weight (lbs)').fill('100')
  await page.getByLabel('Sets').fill('1')
  await page.getByRole('button', { name: 'Save exercise' }).click()
  await page.getByRole('button', { name: 'Finish workout' }).click()
  const [download] = await Promise.all([
    page.waitForEvent('download'),
    page.getByRole('button', { name: 'Export CSV' }).click(),
  ])
  expect(download.suggestedFilename()).toBe('workouts.csv')
  const path = await download.path()
  const fs = await import('node:fs')
  const content = fs.readFileSync(path, 'utf8')
  expect(content).toContain('Exercise,Reps,Weight,Sets')
  expect(content).toContain('Bench Press,8,100,1')
})

test('[A7] filters workouts by search', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Add workout' }).click()
  await page.getByLabel('Exercise').fill('Bench Press')
  await page.getByLabel('Reps').fill('8')
  await page.getByLabel('Weight (lbs)').fill('100')
  await page.getByLabel('Sets').fill('1')
  await page.getByRole('button', { name: 'Save exercise' }).click()
  await page.getByRole('button', { name: 'Finish workout' }).click()
  await page.getByRole('button', { name: 'Add workout' }).click()
  await page.getByLabel('Exercise').fill('Squat')
  await page.getByLabel('Reps').fill('10')
  await page.getByLabel('Weight (lbs)').fill('135')
  await page.getByLabel('Sets').fill('3')
  await page.getByRole('button', { name: 'Save exercise' }).click()
  await page.getByRole('button', { name: 'Finish workout' }).click()
  await page.getByLabel('Search workouts').fill('Squat')
  await expect(page.getByRole('listitem').filter({ hasText: 'Squat' })).toBeVisible()
  await expect(page.getByRole('listitem').filter({ hasText: 'Bench Press' })).toHaveCount(0)
  await page.getByLabel('Search workouts').fill('Bench')
  await expect(page.getByRole('listitem').filter({ hasText: 'Bench Press' })).toBeVisible()
  await expect(page.getByRole('listitem').filter({ hasText: 'Squat' })).toHaveCount(0)
})

