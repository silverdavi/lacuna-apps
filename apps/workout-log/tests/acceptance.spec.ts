import { expect, test } from '@playwright/test'

test('[A1] shows heading and empty state', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Gym Workout Logger' })).toBeVisible()
  await expect(page.getByText('No workouts yet')).toBeVisible()
})

test('[A2] adds an exercise to a workout', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Add workout' }).click()
  await page.getByLabel('Exercise').fill('Bench Press')
  await page.getByLabel('Reps').fill('8')
  await page.getByLabel('Weight (lbs)').fill('100')
  await page.getByLabel('Sets').fill('1')
  await page.getByRole('button', { name: 'Save exercise' }).click()
  const row = page.getByRole('row').filter({ hasText: 'Bench Press' })
  await expect(row.getByText('8')).toBeVisible()
  await expect(row.getByText('100')).toBeVisible()
  await expect(row.getByText('1')).toBeVisible()
  await page.getByRole('button', { name: 'Finish workout' }).click()
  await expect(page.getByRole('listitem').filter({ hasText: 'Bench Press' })).toBeVisible()
})

