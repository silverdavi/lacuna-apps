test('[A9] the last generated result survives a reload', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Min').fill('1')
  await page.getByLabel('Max').fill('10')
  await page.getByRole('button', { name: 'Generate' }).click()
  const value = await page.getByLabel('Result').inputValue()
  expect(value).toMatch(/^[0-9]+$/)
  await page.reload()
  const after = await page.getByLabel('Result').inputValue()
  expect(after).toBe(value)
})
