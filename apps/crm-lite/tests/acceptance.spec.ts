import { expect, test, type Locator, type Page } from '@playwright/test'

// A3: "Type" means a <select> with an accessible name of Type, not a text box.
const adaRow = (page: Page): Locator => page.getByRole('row', { name: /Ada Lovelace/ })

test('[A1] empty app shows the heading, No customers yet, and the active Customers tab', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Simple CRM', exact: true })).toBeVisible()
  await expect(page.getByText('No customers yet', { exact: true })).toBeVisible()
  await expect(page.getByRole('tab', { name: 'Customers', exact: true })).toHaveAttribute('aria-selected', 'true')
})

test('[A2] Add customer with Name, Email, and Company saves a list item and hides No customers yet', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Add customer', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('Ada Lovelace')
  await page.getByLabel('Email', { exact: true }).fill('ada@example.com')
  await page.getByLabel('Company', { exact: true }).fill('Analytical Engines')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  const item = page.getByRole('listitem', { name: /Ada Lovelace/ })
  await expect(item).toContainText('Ada Lovelace')
  await expect(item).toContainText('ada@example.com')
  await expect(page.getByText('No customers yet', { exact: true })).toBeHidden()
})

test('[A3] Log interaction on Ada Lovelace adds an entry with Call and Discussed pricing', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Add customer', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('Ada Lovelace')
  await page.getByLabel('Email', { exact: true }).fill('ada@example.com')
  await page.getByLabel('Company', { exact: true }).fill('Analytical Engines')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await adaRow(page).getByRole('button', { name: 'Log interaction', exact: true }).click()
  await page.getByLabel('Type', { exact: true }).selectOption({ label: 'Call' })
  await page.getByLabel('Notes', { exact: true }).fill('Discussed pricing')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await expect(adaRow(page)).toContainText('Call')
  await expect(adaRow(page)).toContainText('Discussed pricing')
})

