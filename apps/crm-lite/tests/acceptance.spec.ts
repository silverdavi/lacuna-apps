test('[A8] Interactions tab shows a table with Date, Customer, Type, Notes and the logged row', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: 'Add customer', exact: true }).click()
  await page.getByLabel('Name', { exact: true }).fill('Ada Lovelace')
  await page.getByLabel('Email', { exact: true }).fill('ada@example.com')
  await page.getByLabel('Company', { exact: true }).fill('Analytical Engines')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await adaRow(page).getByRole('button', { name: 'Log interaction', exact: true }).click()
  await page.getByLabel('Type', { exact: true }).selectOption({ label: 'Call' })
  await page.getByLabel('Notes', { exact: true }).fill('Discussed pricing')
  await page.getByRole('button', { name: 'Save', exact: true }).click()
  await page.getByRole('tab', { name: 'Interactions', exact: true }).click()
  const table = page.getByRole('table')
  for (const header of ['Date', 'Customer', 'Type', 'Notes']) {
    await expect(table.getByRole('columnheader', { name: header, exact: true })).toBeVisible()
  }
  const row = table.getByRole('row', { name: /Ada Lovelace/ })
  await expect(row).toContainText('Ada Lovelace')
  await expect(row).toContainText('Call')
  await expect(row).toContainText('Discussed pricing')
})

