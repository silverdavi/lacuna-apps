test('[A7] copies the result to the clipboard', async ({ page, context }) => {
  await context.grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.goto('/')
  await page.getByLabel('Current age').fill('30')
  await page.getByLabel('Retirement age').fill('65')
  await page.getByLabel('Current savings').fill('50000')
  await page.getByLabel('Monthly contribution').fill('500')
  await page.getByLabel('Annual return %').fill('7')
  await page.getByRole('button', { name: 'Calculate' }).click()
  await page.getByRole('button', { name: 'Copy result' }).click()
  await expect(page.getByText('Copied to clipboard').first()).toBeVisible()
  const clip = await page.evaluate(() => navigator.clipboard.readText())
  expect(clip).toBe('Projected savings at retirement: $1,482,532.00')
})

