test('[A5] Chart and Table tabs switch views', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Current age').fill('30')
  await page.getByLabel('Retirement age').fill('65')
  await page.getByLabel('Current savings').fill('50000')
  await page.getByLabel('Monthly contribution').fill('500')
  await page.getByLabel('Annual return %').fill('7')
  await page.getByRole('button', { name: 'Calculate' }).click()
  await page.getByRole('tab', { name: 'Chart' }).click()
  await expect(page.locator('[data-point]')).toBeVisible()
  await page.getByRole('tab', { name: 'Table' }).click()
  const table = page.getByRole('table')
  await expect(table).toBeVisible()
  const header = table.getByRole('row').first()
  await expect(header).toContainText('Year')
  await expect(header).toContainText('Contribution')
  await expect(header).toContainText('Growth')
  await expect(header).toContainText('Balance')
})

