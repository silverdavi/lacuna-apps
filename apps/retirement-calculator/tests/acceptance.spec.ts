import { expect, test } from '@playwright/test'

test('[A1] shows the heading and intro text', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: 'Retirement Calculator' })).toBeVisible()
  await expect(
    page.getByText('Enter your details to estimate your retirement savings.').first(),
  ).toBeVisible()
})

test('[A2] calculates the projected savings at 7% return', async ({ page }) => {
  await page.goto('/')
  await page.getByLabel('Current age').fill('30')
  await page.getByLabel('Retirement age').fill('65')
  await page.getByLabel('Current savings').fill('50000')
  await page.getByLabel('Monthly contribution').fill('500')
  await page.getByLabel('Annual return %').fill('7')
  await page.getByRole('button', { name: 'Calculate' }).click()
  await expect(
    page.getByText('Projected savings at retirement: $1,482,532.00').first(),
  ).toBeVisible()
})

